import assert from 'node:assert/strict';

// The same behavior must hold in the real server and the tab-local showcase.
export async function classCreditsScenario(call, evidence, persona = 'alex') {
  const signIn = async who => { assert.equal((await call('/api/demo/session', { persona: who })).status, 200); };
  await signIn(persona);
  const session = await call('/api/me');
  const initial = session.user;
  const claim = { activity: 'office', quantity: 1, date: session.today, course: 'General studies', evidence: 'sample', confirm: true };
  const pendingWork = await call('/api/submissions', { ...claim, title: 'Credit estimate pending office hours' });
  const approvedWork = await call('/api/submissions', { ...claim, title: 'Credit estimate approved office hours' });
  const deniedWork = await call('/api/submissions', { ...claim, title: 'Credit estimate denied office hours' });
  for (const result of [pendingWork, approvedWork, deniedWork]) assert.equal(result.status, 201);
  await signIn('chair');
  assert.equal((await call(`/api/submissions/${approvedWork.submission.id}/review`, { decision: 'approved', points: 2, note: 'Verified office hours.' })).status, 200);
  assert.equal((await call(`/api/submissions/${deniedWork.submission.id}/review`, { decision: 'denied', points: 0, note: 'Attendance not verified.' })).status, 200);
  await signIn(persona);
  const history = [approvedWork, deniedWork].map(result => result.submission.id);
  const historicalBefore = await Promise.all(history.map(async id => (await call(`/api/submissions/${id}`)).submission));
  const checkEstimates = async factor => {
    const work = (await call(`/api/submissions/${pendingWork.submission.id}`)).submission;
    assert.equal(work.estimate, Math.round(work.base * factor * 100) / 100);
    for (const before of historicalBefore) {
      const after = (await call(`/api/submissions/${before.id}`)).submission;
      assert.equal(after.estimate, before.estimate, 'Reviewed estimates remain historical.');
      assert.equal(after.awarded, before.awarded, 'Past awarded points do not change.');
    }
  };
  const sendClass = (name, credits, rest = {}) => call('/api/classes', { name, credits, ...evidence, ...rest });
  for (const credits of [undefined, null, '3', -1, 31, 1.234]) {
    assert.equal((await sendClass('Invalid credits', credits)).status, 422);
  }
  const first = await sendClass('Credit workflow A', 12.25);
  const second = await sendClass('Credit workflow B', 2.75);
  assert.equal(first.status, 201);
  assert.equal(second.status, 201);
  assert.equal(first.class.approvedCredits, null);
  assert.equal(first.class.credits, 12.25);
  assert.equal(first.accountCredits, initial.credits);
  assert.equal(first.creditsManaged, false);
  assert.equal((await call('/api/me')).user.credits, initial.credits, 'Pending classes preserve the prior approved load.');
  assert.equal((await call(`/api/syllabi/${first.class.syllabusId}/review`, { decision: 'approved', version: first.class.version })).status, 403);

  await signIn('chair');
  let queue = await call('/api/syllabi');
  const firstItem = queue.syllabi.find(row => row.id === first.class.syllabusId);
  assert.equal(firstItem.currentAccountCredits, initial.credits);
  assert.equal(firstItem.projectedAccountCredits, 12.25);
  const approval = await call(`/api/syllabi/${firstItem.id}/review`, { decision: 'approved', note: '', version: firstItem.version });
  assert.equal(approval.status, 200);
  assert.equal(approval.syllabus.currentAccountCredits, 12.25);
  const secondItem = (await call('/api/syllabi')).syllabi.find(row => row.id === second.class.syllabusId);
  assert.equal(secondItem.projectedAccountCredits, 15);
  assert.equal((await call(`/api/syllabi/${secondItem.id}/review`, { decision: 'approved', note: '', version: secondItem.version })).status, 200);
  assert.equal((await call(`/api/roster/${persona}/academic-settings`, { tier: 3, credits: 6 })).status, 409);
  assert.equal((await call(`/api/roster/${persona}/academic-settings`, { tier: 3, credits: 15 })).status, 200);
  const members = await call('/api/members');
  assert.equal(members.members.find(row => row.id === persona).creditsManaged, true);

  await signIn(persona);
  assert.equal((await call('/api/me')).user.credits, 15);
  assert.equal((await call('/api/points')).multiplier, 1);
  await checkEstimates(1);
  let classes = await call('/api/classes');
  assert.equal(classes.approvedCredits, 15);
  assert.equal(classes.accountCredits, 15);
  assert.equal(classes.creditsManaged, true);
  let course = classes.classes.find(row => row.id === first.class.id);
  let changed = await sendClass(course.name, 9.25, { classId: course.id, version: course.version });
  assert.equal(changed.status, 201);
  assert.equal(changed.class.approvedCredits, 12.25);
  assert.equal(changed.accountCredits, 15);
  await signIn('chair');
  let pending = (await call('/api/syllabi')).syllabi.find(row => row.id === changed.class.syllabusId);
  assert.equal(pending.projectedAccountCredits, 12);
  assert.equal((await call(`/api/syllabi/${pending.id}/review`, { decision: 'denied', note: 'Please correct the credits.', version: pending.version })).status, 200);
  await signIn(persona);
  assert.equal((await call('/api/me')).user.credits, 15);
  course = (await call('/api/classes')).classes.find(row => row.id === first.class.id);
  changed = await sendClass(course.name, 9.25, { classId: course.id, version: course.version });
  await signIn('chair');
  pending = (await call('/api/syllabi')).syllabi.find(row => row.id === changed.class.syllabusId);
  const decisions = await Promise.all(['approved', 'approved'].map(decision => call(`/api/syllabi/${pending.id}/review`, { decision, note: 'Verified against syllabus.', version: pending.version })));
  assert.deepEqual(decisions.map(row => row.status).sort(), [200, 409]);
  await signIn(persona);
  assert.equal((await call('/api/me')).user.credits, 12);
  assert.equal((await call('/api/points')).multiplier, 1.15);
  await checkEstimates(1.15);
  course = (await call('/api/classes')).classes.find(row => row.id === second.class.id);
  let requested = await call(`/api/classes/${course.id}/archive`, { version: course.version });
  assert.equal(requested.status, 200);
  let removal = requested.classes.find(row => row.id === course.id);
  assert.equal(removal.removalPending, true);
  assert.equal(requested.accountCredits, 12);
  assert.equal((await sendClass(course.name, 0, { classId: course.id, version: removal.version })).status, 409);
  assert.equal((await call(`/api/classes/${course.id}/removal-review`, { decision: 'approved', version: removal.removalVersion })).status, 403);
  await signIn('jordan');
  assert.equal((await call(`/api/classes/${course.id}/archive`, { version: removal.version })).status, 404);
  await signIn('chair');
  queue = await call('/api/syllabi');
  const queuedRemoval = queue.removals.find(row => row.classId === course.id);
  assert.equal(queuedRemoval.currentAccountCredits, 12);
  assert.equal(queuedRemoval.projectedAccountCredits, 9.25);
  assert.equal((await call(`/api/classes/${course.id}/removal-review`, { decision: 'approved', version: 'wrong' })).status, 409);
  assert.equal((await call(`/api/classes/${course.id}/removal-review`, { decision: 'denied', note: 'The class remains enrolled.', version: removal.removalVersion })).status, 200);
  await signIn(persona);
  assert.equal((await call('/api/me')).user.credits, 12);
  course = (await call('/api/classes')).classes.find(row => row.id === course.id);
  assert.equal(course.removalPending, false);
  assert.equal(course.removalReview.note, 'The class remains enrolled.');
  requested = await call(`/api/classes/${course.id}/archive`, { version: course.version });
  removal = requested.classes.find(row => row.id === course.id);
  await signIn('chair');
  assert.equal((await call(`/api/classes/${course.id}/removal-review`, { decision: 'approved', version: removal.removalVersion })).status, 200);
  assert.equal((await call(`/api/classes/${course.id}/removal-review`, { decision: 'approved', version: removal.removalVersion })).status, 409);
  await signIn(persona);
  assert.equal((await call('/api/me')).user.credits, 9.25);
  assert.equal((await call('/api/points')).multiplier, 1.3);
  await checkEstimates(1.3);
  assert.equal((await call('/api/classes')).classes.some(row => row.id === course.id), false);
  const tooMany = await sendClass('Overloaded class', 21);
  await signIn('chair');
  pending = (await call('/api/syllabi')).syllabi.find(row => row.id === tooMany.class.syllabusId);
  assert.equal(pending.projectedAccountCredits, 30.25);
  assert.equal((await call(`/api/syllabi/${pending.id}/review`, { decision: 'approved', note: '', version: pending.version })).status, 422);
  assert.equal((await call('/api/syllabi')).syllabi.find(row => row.id === pending.id).status, 'pending');
  await signIn(persona);
  assert.equal((await call('/api/me')).user.credits, 9.25, 'Rejected total must not partly change the account.');
  course = (await call('/api/classes')).classes.find(row => row.id === tooMany.class.id);
  assert.equal((await call(`/api/classes/${course.id}/archive`, { version: course.version })).classes.some(row => row.id === course.id), false, 'Never-approved classes can be removed immediately.');
}
